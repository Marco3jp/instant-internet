// { 時: [分, ...] } を "HH:MM" の配列に展開する
function expand(table) {
  const out = []
  for (const [h, mins] of Object.entries(table)) {
    for (const m of mins) {
      out.push(`${String(h).padStart(2, "0")}:${String(m).padStart(2, "0")}`)
    }
  }
  return out
}

// 便の配列を作る。extra は各便に共通で付ける属性
function trips(table, extra) {
  return expand(table).map(t => ({ t, ...extra }))
}

